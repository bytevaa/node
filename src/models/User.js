// Подключаем библиотеку Mongoose для работы с MongoDB
import mongoose from "mongoose"

// Создаем схему, определяющую структуру и правила валидации документа пользователя
const userSchema = new mongoose.Schema({
  // Имя пользователя
  firstName: {
    type: String,      // Значение должно быть строкой
    required: true,    // Обязательное поле при регистрации
    trim: true,        // Автоматически удаляет пробелы в начале и конце строки
  },

  // Фамилия пользователя
  lastName: {
    type: String,      // Значение должно быть строкой
    required: true,    // Обязательное поле при регистрации
    trim: true,        // Автоматически удаляет пробелы в начале и конце строки
  },

  // Поле электронной почты
  email: {
    type: String,      // Значение должно быть строкой
    required: true,    // Обязательное поле при создании записи
    unique: true,      // Гарантирует уникальность email в базе (создает уникальный индекс)
    trim: true,        // Автоматически удаляет пробелы в начале и конце строки
    lowercase: true,   // Приводит все символы к нижнему регистру перед сохранением
  },

  // Поле пароля
  password: {
    type: String,      // Значение должно быть строкой
    required: true,    // Обязательное поле
    minlength: 6,      // Минимальная длина пароля — 6 символов
    select: false,     // Не возвращать это поле при обычных запросах (например, User.find()) для безопасности
    trim: true,        // Удаляет случайные пробелы по краям строки
  },

  // Поле ссылки на аватар
  avatar: {
    type: String,      // Хранит URL изображения или путь к файлу в виде строки
    default: "",       // Значение по умолчанию (пустая строка), если аватар не передан
  },

  // Поле роли пользователя для разграничения прав доступа
  role: {
    type: String,               // Значение должно быть строкой
    enum: ["user", "admin"],    // Разрешены только перечисленные значения
    default: "user",            // По умолчанию каждому новому пользователю присваивается роль "user"
  },
})

// Компилируем схему в модель "User" (в MongoDB создастся коллекция "users") и экспортируем её
export default mongoose.model("User", userSchema)
